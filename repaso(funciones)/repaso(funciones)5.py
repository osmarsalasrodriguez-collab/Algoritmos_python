# Problema 5: Longitud de un nombre
# Cuenta cuántas letras tiene una cadena usando len().
# --------------------------------------------------
def longitud_nombre(nombre):
    # len() nos dice cuantas letras tiene
    return len(nombre)

# Pruebas
print(longitud_nombre("Osmar")) 
print(longitud_nombre("Omar"))   
print(longitud_nombre(""))      
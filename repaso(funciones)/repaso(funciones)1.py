# Problema 1: Función para saludar
# Recibe un nombre y regresa un mensaje de saludo.
# ------------------------------------------------
def saludar(nombre):
    # pegamos el texto con el nombre
    return f"Hola, {nombre}!"


# Pruebas llamando a la funcion y el nombre
print(saludar("Carlos")) # "Hola, Carlos!"
print(saludar("Ana"))    # "Hola, Ana!"
print(saludar("Mundo"))  # "Hola, Mundo!"

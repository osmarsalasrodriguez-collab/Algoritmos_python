# Problema 3: Repetir un texto
# Multiplica una cadena por un número para repetirla.
# --------------------------------------------------
def repetir_texto(texto, veces):
    # en python se puede multiplicar un texto por un numero
    return texto * veces

# Pruebas
print(repetir_texto("Eco", 3))  
print(repetir_texto("Hola", 1)) 
print(repetir_texto("Ja", 4))   
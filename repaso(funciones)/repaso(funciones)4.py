# Problema 4: Obtener el doble de un número
# Recibe un número y lo multiplica por 2.
# --------------------------------------------------
def obtener_doble(n):
    # multiplicamos por 2
    return n * 2

# Pruebas
print(obtener_doble(14)) 
print(obtener_doble(0))  
print(obtener_doble(-5)) 
# Problema 2: Función para sumar dos números
# Recibe dos números y regresa el resultado de la suma.
# --------------------------------------------------
def sumar(a, b):
    # sumamos a y b
    return a + b

# Pruebas
print(sumar(8, 5))   # 13
print(sumar(-3, 10)) # 7
print(sumar(0, 0))   # 0